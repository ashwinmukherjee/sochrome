// Writes THIRD_PARTY.md, public/third-party-licenses.txt and public/credits.txt from src/third-party.json and
// package-lock.json.

import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { BRAND } from "../src/brand";
import record from "../src/third-party.json";
import { CREDITS_WORDS } from "./third-party-words";

const ROOT = resolve(import.meta.dirname, "..");
const lock = JSON.parse(readFileSync(resolve(ROOT, "package-lock.json"), "utf8")) as {
  packages: Record<string, { version?: string; license?: string; dev?: boolean; resolved?: string }>;
};

interface Entry {
  name: string;
  by: string;
  version: string;
  licence: string;
  link: string;
  redistribution: string;
  shipped: boolean;
  credit: string;
  flags: string[];
}

const cell = (s: string) => s.replaceAll("|", "\\|");
const table = (rows: Entry[]) =>
  [
    "| Name | By | Version | Licence | Link | Redistribution | Shipped |",
    "|---|---|---|---|---|---|---|",
    ...rows.map(
      (e) =>
        `| ${[e.name, e.by, e.version, e.licence, e.link, e.redistribution, e.shipped ? "yes" : "no"].map(cell).join(" | ")} |`,
    ),
  ].join("\n");

const packages = Object.entries(lock.packages)
  .filter(([path]) => path.startsWith("node_modules/"))
  .map(([path, p]) => ({
    name: path.replace(/^.*node_modules\//, ""),
    version: p.version ?? "",
    licence: p.license ?? "UNKNOWN",
    dev: !!p.dev,
  }))
  .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
const runtime = packages.filter((p) => !p.dev);
const COPYLEFT = /GPL|AGPL|LGPL|MPL|EPL|CDDL|SSPL/i;
const RESTRICTED = /\b(NC|ND)\b|NonCommercial|NoDerivatives|UNKNOWN|UNLICENSED|SEE LICENSE/i;
const flaggedPackages = packages.filter((p) => COPYLEFT.test(p.licence) || RESTRICTED.test(p.licence));

const all: Entry[] = [...record.data, ...record.models, ...record.fonts];
const isFlag = (f: string) => /^(FLAGGED|UNVERIFIED)/.test(f);
const flags = all.flatMap((e) => e.flags.filter(isFlag).map((f) => `- **${e.name}.** ${f}`));
const notes = all.flatMap((e) => e.flags.filter((f) => !isFlag(f)).map((f) => `- **${e.name}.** ${f}`));

const md = [
  "# Third-party data, models, fonts and code",
  "",
  "Generated by `npm run third-party` from `src/third-party.json` and `package-lock.json`. Edit those, never this file.",
  "",
  // The section stands only while something is flagged.
  ...(flags.length + flaggedPackages.length
    ? [
        "## Flagged",
        "",
        "Nothing here is resolved silently. Each item is open until its owner settles it.",
        "",
        ...flags,
        ...flaggedPackages.map(
          (p) => `- **${p.name} ${p.version}** (${p.dev ? "development only" : "shipped"}). Licence: ${p.licence}.`,
        ),
        "",
      ]
    : []),
  "## Notes",
  "",
  ...notes,
  "",
  "## Data",
  "",
  "Upstream data keeps its own licence. The data bundle is built from these sources and is not committed to this repository.",
  "",
  table(record.data),
  "",
  "## Models and APIs",
  "",
  table(record.models),
  "",
  "## Fonts",
  "",
  table(record.fonts),
  "",
  "## Credits, as public/credits.txt gives them",
  "",
  ...all.filter((e) => e.shipped && e.credit).map((e) => `- ${e.credit}`),
  "",
  "## Code that ships in the app",
  "",
  "| Package | Version | Licence |",
  "|---|---|---|",
  ...runtime.map((p) => `| ${p.name} | ${p.version} | ${p.licence} |`),
  "",
  "## Code used only to build and check",
  "",
  `${packages.length - runtime.length} packages, none of them shipped. Licences in use: ${[...new Set(packages.filter((p) => p.dev).map((p) => p.licence))].sort().join(", ")}.`,
  "",
].join("\n");
writeFileSync(resolve(ROOT, "THIRD_PARTY.md"), md);

/** The notices of everything that ships, as their licences require. */
const notices = runtime.map((p) => {
  const dir = resolve(ROOT, "node_modules", p.name);
  const file = existsSync(dir) ? readdirSync(dir).find((f) => /^(licen[cs]e|copying)(\.|$)/i.test(f)) : undefined;
  const text = file
    ? readFileSync(resolve(dir, file), "utf8").trim()
    : `(${p.licence}; no licence file in the package)`;
  return `${p.name} ${p.version}\n${"-".repeat(`${p.name} ${p.version}`.length)}\n${text}\n`;
});
writeFileSync(resolve(ROOT, "public/third-party-licenses.txt"), notices.join("\n"));

const shipped = [...record.data, ...record.fonts, ...record.models].filter((e) => e.shipped);
/** The contact line waits for the address: a placeholder is never written. */
const email = BRAND.email.includes("{{") ? null : BRAND.email;
// What it is and what happens to a file, then the credits, then the licence under its owner's copyright. The
// product's name stands only in src/brand.ts and what is built from it (Q1).
const credits = [
  `${BRAND.name} ${CREDITS_WORDS.disclaimer}`,
  "",
  CREDITS_WORDS.statement,
  "",
  "CREDITS",
  "",
  ...shipped.flatMap((e) => [e.name, e.credit || `${e.name} (${e.by}).`, ...(e.link ? [e.link] : []), ""]),
  "LICENCE",
  "",
  `Copyright ${BRAND.year} ${BRAND.owner}.`,
  CREDITS_WORDS.terms,
  "Code: PolyForm Noncommercial 1.0.0, https://polyformproject.org/licenses/noncommercial/1.0.0",
  "Copy, narrative text, graphics and visual design: CC BY-NC-ND 4.0, https://creativecommons.org/licenses/by-nc-nd/4.0/",
  "Data, models, fonts and dependencies keep their own licences. Open-source notices: /third-party-licenses.txt",
  ...(email ? [`For anything else, contact ${email}.`] : []),
  "",
].join("\n");
writeFileSync(resolve(ROOT, "public/credits.txt"), credits);

process.stdout.write(
  `THIRD_PARTY.md: ${all.length} sources, ${flags.length + flaggedPackages.length} flagged; ${runtime.length} shipped packages, ${packages.length - runtime.length} for the build\n`,
);
